"""Files that unplugin-vue-components and unplugin-auto-import register.

Those Vite plugins make a component or a composable available everywhere
without an import, so nothing imports it. They record what they registered
in a generated declaration file (``components.d.ts``, ``auto-imports.d.ts``)
as ``typeof import('./components/TheFooter.vue')``; a file named there is an
entry point, wherever the plugin's ``dirs`` option put it.
"""

from __future__ import annotations

import re
from pathlib import Path

from desloppify.base.discovery.file_paths import resolve_path
from desloppify.base.discovery.source import find_source_files
from desloppify.languages.typescript.detectors.deps.resolve import resolve_target

_GENERATED_MARK = "Generated by unplugin-"
_RELATIVE_IMPORT_RE = re.compile(r"""\bimport\(\s*['"](\.{1,2}/[^'"]+)['"]\s*\)""")


def auto_import_entries(path: Path) -> set[str]:
    """Absolute paths of the files the plugins' generated declarations name."""
    entries: set[str] = set()
    for filepath in find_source_files(path, [".d.ts"]):
        full = Path(resolve_path(filepath))
        try:
            text = full.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if _GENERATED_MARK not in text[:2000]:
            continue
        for specifier in set(_RELATIVE_IMPORT_RE.findall(text)):
            target = resolve_target(full.parent / specifier)
            if target is not None:
                entries.add(target)
    return entries


__all__ = ["auto_import_entries"]
